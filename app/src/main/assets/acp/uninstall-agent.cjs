/* Host-owned package removal. No ACP session or user-data deletion lives here. */
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const MARKER = '__OMNI_AGENT_UNINSTALL__';
const PLANS = Object.freeze({
  'claude-code': { packages: ['@anthropic-ai/claude-code', '@agentclientprotocol/claude-agent-acp'], commands: ['claude', 'claude-agent-acp'] },
  codex: { packages: ['@openai/codex', '@agentclientprotocol/codex-acp'], commands: ['codex', 'codex-acp'] },
  opencode: { packages: ['@opencode/cli', 'opencode-ai'], commands: ['opencode', 'opencode2'] },
  // Retired runtime: retained only for cleanup of previously managed installs.
  'deepseek-harness': {
    packages: ['@deepseek-ai/dsh', '@openma/deepseek-harness-acp', '@deepseek-ai/dsh-acp-demo'],
    commands: ['dsh', 'dsh-acp-android', 'dsh-acp', 'dsh-acp-demo'],
  },
  pi: { packages: [], commands: ['omnibot-pi-acp'] },
  'kimi-code': { packages: ['@moonshot-ai/kimi-code'], commands: ['kimi'] },
});

function stat(file) {
  try { return fs.lstatSync(file); } catch (error) {
    if (error.code === 'ENOENT') return undefined;
    throw error;
  }
}

function inside(parent, file) {
  const relative = path.relative(parent, file);
  return relative === '' || (relative !== '..' && !relative.startsWith(`..${path.sep}`) && !path.isAbsolute(relative));
}

// A root override is an exported test seam only. The CLI always uses '/'.
function layoutFor(root = '/') {
  root = fs.realpathSync(root);
  const at = (file) => path.join(root, file);
  const prefix = at('/root/.npm-global');
  return {
    root, prefix, bin: path.join(prefix, 'bin'), modules: path.join(prefix, 'lib/node_modules'),
    systemBin: at('/usr/local/bin'),
    piVersions: at('/root/.local/share/omnibot/pi-acp/versions'),
    piInstaller: at('/root/.local/share/omnibot/install-pi-acp.sh'),
  };
}

function safeParents(layout, file, includeLeaf = false) {
  if (!inside(layout.root, file)) throw new Error(`Path is outside the terminal environment: ${file}`);
  const parts = path.relative(layout.root, file).split(path.sep).filter(Boolean);
  let current = layout.root;
  for (const part of parts.slice(0, includeLeaf ? parts.length : -1)) {
    current = path.join(current, part);
    const item = stat(current);
    if (!item) return;
    if (item.isSymbolicLink() || !item.isDirectory()) {
      throw new Error(`Refusing a redirected installation directory: ${current}`);
    }
  }
}

function ownedWrapper(strategy, file, layout) {
  const item = stat(file);
  if (!item?.isFile() || item.size > 65536) return false;
  const source = fs.readFileSync(file, 'utf8');
  if (strategy === 'pi') {
    const escaped = layout.piVersions.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    return new RegExp(`^#!/bin/sh\\nexec node '${escaped}/[a-f0-9]{20}/dist/index\\.js' "\\$@"\\n?$`).test(source);
  }
  if (strategy === 'deepseek-harness') {
    if (path.basename(file) !== 'dsh-acp-android') return false;
    const entry = path.join(layout.modules, '@deepseek-ai/dsh/lib/bin.js');
    const launch = `exec node --expose-internals ${entry} "$@"\n`;
    const legacyPatch = path.join(layout.root, 'root/.dsh/omnibot-acp/omnibot-acp-headless.patch.yml');
    return source === '#!/bin/sh\n' + launch || source === '#!/bin/sh\n' +
      'export DSH_BUNDLED_SKILL_DIR="${DSH_BUNDLED_SKILL_DIR:-$DSH_HOME/omnibot-bundled-skills}"\n' + launch ||
      source === `#!/bin/sh\nexec node --expose-internals ${entry} --patch "${legacyPatch}" "$@"\n`;
  }
  return false;
}

function ownedPiInstaller(file) {
  const item = stat(file);
  if (!item?.isFile() || item.size > 1024 * 1024) return false;
  const source = fs.readFileSync(file, 'utf8');
  return source.includes('# Generated by tools/pi-acp/scripts/package-android.mjs. Do not edit.\n') &&
    source.includes('PI_ACP_RUNTIME_ROOT="${OMNIBOT_PI_INSTALL_ROOT:-/root/.local/share/omnibot/pi-acp}"') &&
    source.includes("node <<'OMNIBOT_PI_LAUNCHER'");
}

function contextFor(strategy, options = {}) {
  if (!Object.hasOwn(PLANS, strategy)) throw new Error('This Agent does not support managed uninstallation.');
  const layout = layoutFor(options.root);
  const plan = PLANS[strategy];
  const packageRoots = plan.packages.map((name) => path.join(layout.modules, name));
  const ownedRoots = strategy === 'pi' ? [layout.piVersions] : packageRoots;
  const searchPath = options.searchPath ?? (process.env.PATH || '').split(path.delimiter).filter(Boolean);
  return { strategy, layout, plan, packageRoots, ownedRoots, searchPath: [...new Set([layout.bin, layout.systemBin, ...searchPath])] };
}

function ownedEntry(context, file, systemLink = false) {
  const item = stat(file);
  if (!item) return false;
  if (!item.isSymbolicLink()) return ownedWrapper(context.strategy, file, context.layout);
  const destination = path.resolve(path.dirname(file), fs.readlinkSync(file));
  if (context.ownedRoots.some((root) => inside(root, destination))) return true;
  if (!systemLink || path.dirname(destination) !== context.layout.bin) return false;
  // A setup-created /usr/local/bin alias is ours only while the prefix entry
  // is ours (or already absent), never when it points at a foreign replacement.
  return context.plan.commands.includes(path.basename(destination)) &&
    (!stat(destination) || ownedEntry(context, destination));
}

function managedEntries(context) {
  const entries = [];
  for (const directory of [context.layout.bin, context.layout.systemBin]) {
    safeParents(context.layout, directory, true);
    if (!stat(directory)) continue;
    for (const name of fs.readdirSync(directory)) {
      const file = path.join(directory, name);
      if (ownedEntry(context, file, directory === context.layout.systemBin)) entries.push(file);
    }
  }
  return entries;
}

function executable(file) {
  try {
    if (!fs.statSync(file).isFile()) return false;
    fs.accessSync(file, fs.constants.X_OK);
    return true;
  } catch { return false; }
}

function inspect(context) {
  const errors = [];
  let managedFilesRemain = false;
  const check = (action) => {
    try { return action(); } catch (error) {
      managedFilesRemain = true;
      errors.push(error.message);
      return undefined;
    }
  };
  for (const root of context.ownedRoots) check(() => {
    safeParents(context.layout, root, true);
    if (stat(root)) managedFilesRemain = true;
  });
  check(() => { if (managedEntries(context).length) managedFilesRemain = true; });
  if (context.strategy === 'pi') check(() => {
    safeParents(context.layout, context.layout.piInstaller);
    if (ownedPiInstaller(context.layout.piInstaller)) managedFilesRemain = true;
  });
  const externalCommands = [];
  let commandPresent = false;
  for (const name of context.plan.commands) {
    for (const directory of context.searchPath) {
      const file = path.join(directory, name);
      if (!executable(file)) continue;
      commandPresent = true;
      const managedLocation = directory === context.layout.bin || directory === context.layout.systemBin;
      const owned = managedLocation && check(() => ownedEntry(context, file, directory === context.layout.systemBin));
      if (!owned) externalCommands.push(file);
    }
  }
  return { managedFilesRemain, commandPresent, externalCommands: [...new Set(externalCommands)], errors };
}

// npm removes a package's declared bin/man paths without checking who owns
// the current entries. Reject foreign replacements before invoking npm.
function verifyNpmRemoval(context) {
  const { layout } = context;
  safeParents(layout, layout.prefix, true);
  safeParents(layout, layout.bin, true);
  for (const packageRoot of context.packageRoots) {
    safeParents(layout, packageRoot, true);
    const metadata = path.join(packageRoot, 'package.json');
    const item = stat(metadata);
    if (!item) continue; // Interrupted installs can have no manifest yet.
    if (!item.isFile()) throw new Error(`Refusing redirected package metadata: ${metadata}`);
    const pkg = JSON.parse(fs.readFileSync(metadata, 'utf8'));
    const expected = path.relative(layout.modules, packageRoot).split(path.sep).join('/');
    if (pkg.name !== expected) throw new Error(`Package identity does not match its managed directory: ${metadata}`);
    const names = typeof pkg.bin === 'string' ? [path.basename(expected)] : Object.keys(pkg.bin || {});
    const paths = names.map((name) => {
      if (name !== path.basename(name) || name.includes('\\') || name === '.' || name === '..') throw new Error('Invalid installed package command name.');
      return path.join(layout.bin, name);
    });
    for (const man of Array.isArray(pkg.man) ? pkg.man : []) {
      if (typeof man !== 'string' || !/.\.[0-9]+(\.gz)?$/.test(man)) continue;
      const section = path.extname(path.basename(man, '.gz')).slice(1);
      paths.push(path.join(layout.prefix, 'share/man', `man${section}`, path.basename(man)));
    }
    for (const file of paths) {
      safeParents(layout, file);
      if (stat(file) && !ownedEntry(context, file)) throw new Error(`A non-managed command or manual page was preserved: ${file}`);
    }
  }
}

function defaultRunNpm(args) {
  return spawnSync('npm', args, { encoding: 'utf8', timeout: 360000, maxBuffer: 32768 });
}

function uninstallAgent(strategy, options = {}) {
  let context;
  try { context = contextFor(strategy, options); } catch (error) {
    return { ok: false, managedFilesRemain: false, commandPresent: false, externalCommands: [], error: error.message };
  }
  const errors = [];
  if (!options.probe) try {
    const before = inspect(context);
    if (before.errors.length) throw new Error(before.errors.join('\n'));
    verifyNpmRemoval(context);
    const installedPackages = context.plan.packages.filter((_, index) => stat(context.packageRoots[index]));
    if (installedPackages.length) {
      const args = ['uninstall', '-g', '--prefix', context.layout.prefix, '--ignore-scripts', '--offline', '--no-audit', '--no-fund', ...installedPackages];
      const result = (options.runNpm || defaultRunNpm)(args);
      if (result.error || result.status !== 0) {
        const detail = result.error?.message || result.stderr?.trim() || `exit ${result.status}`;
        throw new Error(`Package removal failed: ${detail.slice(0, 3000)}`);
      }
    }
    // Capture aliases before unlinking the prefix entry they refer to.
    const entries = managedEntries(context);
    if (context.strategy === 'pi') {
      safeParents(context.layout, context.layout.piVersions, true);
      fs.rmSync(context.layout.piVersions, { recursive: true, force: true });
      safeParents(context.layout, context.layout.piInstaller);
      if (ownedPiInstaller(context.layout.piInstaller)) fs.unlinkSync(context.layout.piInstaller);
    }
    for (const entry of entries) {
      safeParents(context.layout, entry);
      if (stat(entry)) fs.unlinkSync(entry);
    }
  } catch (error) { errors.push(error.message); }
  const state = inspect(context);
  errors.push(...state.errors);
  if (state.externalCommands.length) errors.push(`Other installations were preserved: ${state.externalCommands.join(', ')}`);
  if (!options.probe && !errors.length && (state.managedFilesRemain || state.commandPresent)) errors.push('Managed installation files or commands remain. Retry uninstallation.');
  return {
    ok: errors.length === 0 && !state.managedFilesRemain && !state.commandPresent,
    managedFilesRemain: state.managedFilesRemain,
    commandPresent: state.commandPresent,
    externalCommands: state.externalCommands,
    ...(errors.length ? { error: [...new Set(errors)].join('\n') } : {}),
  };
}

function main(args) {
  const valid = args.length === 1 || (args.length === 2 && args[1] === '--probe');
  const result = valid ? uninstallAgent(args[0], { probe: args[1] === '--probe' }) : {
    ok: false, managedFilesRemain: false, commandPresent: false, externalCommands: [], error: 'Invalid managed uninstall arguments.',
  };
  process.stdout.write(`${MARKER}${JSON.stringify(result)}\n`);
  process.exitCode = result.error ? 1 : 0;
}

module.exports = { uninstallAgent, layoutFor };
if (require.main === module || module.id === '[eval]') main(process.argv.slice(module.id === '[eval]' ? 1 : 2));
