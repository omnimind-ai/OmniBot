import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
import { matchesAndroidInstaller } from "./installer-validation.mjs";

const root = fileURLToPath(new URL("..", import.meta.url));
const repo = resolve(root, "../..");
const files = Object.fromEntries([
  "package.json", "package-lock.json", "LICENSE",
  ...readdirSync(join(root, "dist")).filter((file) => file.endsWith(".js")).sort().map((file) => `dist/${file}`),
].map((file) => [file, readFileSync(join(root, file), "utf8")]));
const archive = JSON.stringify(files);
const digest = createHash("sha256").update(archive).update(readFileSync(fileURLToPath(import.meta.url))).digest("hex").slice(0, 20);
const payload = gzipSync(archive, { level: 9 }).toString("base64");
// A self-contained asset keeps deployment on the existing catalog installer
// seam. There is no npm publication or network download of adapter source.
const installer = `# Generated by tools/pi-acp/scripts/package-android.mjs. Do not edit.
set -eu
node -e 'const [major, minor] = process.versions.node.split(".").map(Number); if (major < 22 || (major === 22 && minor < 19)) { console.error("Pi requires Node.js >= 22.19.0"); process.exit(1); }'
if ! command -v bash >/dev/null 2>&1 || ! command -v rg >/dev/null 2>&1; then
  if command -v apk >/dev/null 2>&1; then
    apk add --no-cache bash ripgrep
  elif command -v apt-get >/dev/null 2>&1; then
    DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends bash ripgrep
  else
    printf '%s\\n' 'Pi requires bash and ripgrep' >&2
    exit 1
  fi
fi
PI_ACP_RUNTIME_ROOT="\${OMNIBOT_PI_INSTALL_ROOT:-/root/.local/share/omnibot/pi-acp}"
PI_ACP_PACKAGE_DIR="$PI_ACP_RUNTIME_ROOT/versions/${digest}"
PI_ACP_BIN_DIR="\${OMNIBOT_PI_BIN_DIR:-/root/.npm-global/bin}"
export PI_ACP_PACKAGE_DIR PI_ACP_BIN_DIR
node <<'OMNIBOT_PI_EXTRACT'
const fs = require('node:fs');
const path = require('node:path');
const files = JSON.parse(require('node:zlib').gunzipSync(Buffer.from('${payload}', 'base64')).toString());
for (const [name, content] of Object.entries(files)) {
  const destination = path.join(process.env.PI_ACP_PACKAGE_DIR, name);
  fs.mkdirSync(path.dirname(destination), {recursive: true, mode: 0o700});
  fs.writeFileSync(destination, content, {mode: 0o600});
}
OMNIBOT_PI_EXTRACT
if ! node "$PI_ACP_PACKAGE_DIR/dist/index.js" --health >/dev/null 2>&1; then
  (
    cd "$PI_ACP_PACKAGE_DIR"
    npm ci --omit=dev --ignore-scripts --no-audit --no-fund --registry="\${OMNIBOT_NPM_REGISTRY:-https://registry.npmmirror.com}" ||
      npm ci --omit=dev --ignore-scripts --no-audit --no-fund --registry=https://registry.npmjs.org
  )
fi
node "$PI_ACP_PACKAGE_DIR/dist/index.js" --health
node <<'OMNIBOT_PI_LAUNCHER'
const fs = require('node:fs');
const path = require('node:path');
const quote = value => "'" + value.replaceAll("'", "'\\\"'\\\"'") + "'";
fs.mkdirSync(process.env.PI_ACP_BIN_DIR, {recursive: true});
const launcher = path.join(process.env.PI_ACP_BIN_DIR, 'omnibot-pi-acp');
fs.writeFileSync(launcher + '.next', '#!/bin/sh\\nexec node ' + quote(path.join(process.env.PI_ACP_PACKAGE_DIR, 'dist/index.js')) + ' "$@"\\n', {mode: 0o755});
fs.renameSync(launcher + '.next', launcher);
OMNIBOT_PI_LAUNCHER
`;
const asset = join(repo, "app/src/main/assets/acp/install/pi.sh");
const catalogPath = join(repo, "app/src/main/assets/acp/agents.json");
const catalog = JSON.parse(readFileSync(catalogPath, "utf8"));
const entry = catalog.agents.find((entry) => entry.id === "pi-acp");
const revision = `pi-1.4.0-${digest}`;
if (process.argv.includes("--check")) {
  if (!matchesAndroidInstaller(readFileSync(asset, "utf8"), installer, archive) || entry.runtime.preparationRevision !== revision) {
    throw new Error("Pi Android asset is stale. Run npm run package:android in tools/pi-acp.");
  }
} else {
  writeFileSync(asset, installer);
  // Preserve catalog formatting outside this generated revision.
  const previous = entry.runtime.preparationRevision;
  writeFileSync(catalogPath, readFileSync(catalogPath, "utf8").replace(JSON.stringify(previous), JSON.stringify(revision)));
}
console.log(`Pi Android installer ${revision}: ${Buffer.byteLength(installer)} bytes`);
